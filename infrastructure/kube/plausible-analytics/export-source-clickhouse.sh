#!/bin/sh
# Read-only helpers against Plausible's ClickHouse StatefulSet on the Platform
# Cluster, for the migration to the shared ClickHouse Cloud service
# (README.md, "Migrating ClickHouse to ClickHouse Cloud").
#
# Usage: export-source-clickhouse.sh <stage|prod> sizes|ddl|preflight
#
#   sizes      Active parts per table and partition: rows, bytes on disk,
#              uncompressed bytes. Plus one total per table.
#   ddl        SHOW CREATE TABLE for every table in the database, rewritten
#              for ClickHouse Cloud (Replicated* engines lose their parameters,
#              TinyLog becomes MergeTree ORDER BY tuple(), CREATE TABLE gets
#              IF NOT EXISTS), as one SQL file on stdout.
#   preflight  Proves the pod can open a TLS native-protocol connection to the
#              Cloud service: SELECT version() through remoteSecure().
#
# Environment:
#   KUBECONTEXT                     kubectl context (default: the env name)
#   POD                             ClickHouse pod (default: plausible-analytics-clickhouse-0)
#   DATABASE                        Plausible's database (default: plausible_events_db)
#   CLICKHOUSE_CLOUD_HOST           preflight: the service hostname (no scheme, no port)
#   CLICKHOUSE_CLOUD_ADMIN_PASSWORD preflight: the `default` user's password
#                                   (SHORT_LINKS_CLICKHOUSE_ADMIN_PASSWORD in Doppler `core`)
#
# Nothing here writes to either side.

set -eu

usage() {
  echo "usage: $0 <stage|prod> sizes|ddl|preflight" >&2
  exit 2
}

[ $# -eq 2 ] || usage
env_name=$1
command_name=$2
case $env_name in
  stage | prod) ;;
  *) usage ;;
esac

kube_context=${KUBECONTEXT:-$env_name}
pod=${POD:-plausible-analytics-clickhouse-0}
database=${DATABASE:-plausible_events_db}
cluster_name="jfp-eks-$env_name"

for tool in kubectl jq; do
  command -v "$tool" >/dev/null 2>&1 || {
    echo "$tool is required" >&2
    exit 1
  }
done

# Guard against a kubectl context that points at the other cluster.
context_cluster=$(kubectl config view -o json |
  jq -r --arg ctx "$kube_context" '.contexts[] | select(.name == $ctx) | .context.cluster')
case $context_cluster in
  */"$cluster_name") ;;
  *)
    echo "kubectl context '$kube_context' points at '$context_cluster', not $cluster_name" >&2
    exit 1
    ;;
esac

# query <sql> [format]: run one statement in the pod, result on stdout. No -i:
# the statement travels in --query, and an attached stdin would swallow the
# table list the ddl loop reads.
query() {
  if [ $# -ge 2 ]; then
    kubectl --context "$kube_context" exec "$pod" -- \
      clickhouse-client --query "$1" --format "$2"
  else
    kubectl --context "$kube_context" exec "$pod" -- \
      clickhouse-client --query "$1"
  fi
}

sizes() {
  query "
    SELECT table, partition, sum(rows) AS rows,
           formatReadableSize(sum(bytes_on_disk)) AS on_disk,
           formatReadableSize(sum(data_uncompressed_bytes)) AS uncompressed,
           min(min_time) AS min_time, max(max_time) AS max_time
    FROM system.parts
    WHERE database = '$database' AND active
    GROUP BY table, partition
    ORDER BY table, partition" PrettyCompactMonoBlock
  echo
  query "
    SELECT table, sum(rows) AS rows,
           formatReadableSize(sum(bytes_on_disk)) AS on_disk,
           formatReadableSize(sum(data_uncompressed_bytes)) AS uncompressed,
           count() AS active_parts
    FROM system.parts
    WHERE database = '$database' AND active
    GROUP BY table
    ORDER BY sum(bytes_on_disk) DESC" PrettyCompactMonoBlock
  echo
  query "SELECT name, engine FROM system.tables WHERE database = '$database' ORDER BY name" PrettyCompactMonoBlock
}

ddl() {
  echo "-- Generated by $(basename "$0") $env_name ddl on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "-- from $pod on $cluster_name. Plausible's own migrations own this schema"
  echo "-- from the first start against ClickHouse Cloud; this file is the"
  echo "-- migration-time snapshot used to create the tenant (README.md)."
  echo "CREATE DATABASE IF NOT EXISTS $database;"
  echo
  query "SELECT name FROM system.tables WHERE database = '$database' ORDER BY name" TSVRaw |
    while IFS= read -r table; do
      # TSVRaw keeps the statement's newlines. The engine rewrites:
      #   ReplicatedMergeTree('/path', '{replica}')                      -> MergeTree()
      #   ReplicatedVersionedCollapsingMergeTree('/p', '{r}', sign, events) -> VersionedCollapsingMergeTree(sign, events)
      #   TinyLog (Ecto's schema_migrations)                               -> MergeTree ORDER BY tuple()
      # Cloud maps the MergeTree family to its Shared* equivalents itself.
      query "SHOW CREATE TABLE $database.$table" TSVRaw |
        sed \
          -e "1s/^CREATE TABLE $database\.$table/CREATE TABLE IF NOT EXISTS $database.$table/" \
          -e "s/ENGINE = Replicated\([A-Za-z]*MergeTree\)('[^']*', *'[^']*'\(, *\)\{0,1\}/ENGINE = \1(/" \
          -e 's/ENGINE = TinyLog$/ENGINE = MergeTree ORDER BY tuple()/'
      echo ";"
      echo
    done
}

preflight() {
  : "${CLICKHOUSE_CLOUD_HOST:?set CLICKHOUSE_CLOUD_HOST to the Cloud service hostname}"
  : "${CLICKHOUSE_CLOUD_ADMIN_PASSWORD:?set CLICKHOUSE_CLOUD_ADMIN_PASSWORD}"
  # The password is visible in the pod's process list for the duration of the
  # statement; acceptable for a one-off against a password that lives in Doppler.
  query "SELECT version() AS cloud_version
         FROM remoteSecure('$CLICKHOUSE_CLOUD_HOST:9440', system, one, 'default', '$CLICKHOUSE_CLOUD_ADMIN_PASSWORD')" PrettyCompactMonoBlock
  echo "pod $pod can reach $CLICKHOUSE_CLOUD_HOST:9440 over TLS; the push route works."
  echo "(An idled stage service makes the first attempt time out: rerun.)"
}

case $command_name in
  sizes) sizes ;;
  ddl) ddl ;;
  preflight) preflight ;;
  *) usage ;;
esac
